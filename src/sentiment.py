"""Station 3 - Sentiment model: the AlphaStream FinSent lexicon, headline
scoring, and the sector sentiment index.

Design:
    * Baseline model is VADER (nltk), the model the course baseline uses.
    * AlphaStream FinSent is a curated finance-aware extension: single words
      enter the analyser's lexicon, multi-word phrases enter VADER's
      SPECIAL_CASES (with a small supporting head word so the phrase is
      actually looked up), and finance intensity words enter BOOSTER_DICT.
      Nothing is stripped from the text before scoring - VADER reads casing,
      punctuation, and negation, and stripping them destroys the signal.
    * Headlines are scored per unique title (many rows repeat a title across
      tickers), aggregated to a ticker-day mean, then to an equal-weight
      sector index. Ticker-days with no headlines contribute neutral (0) to
      the sector mean; we also report the fraction of names with news that day
      so coverage is visible.
    * Look-ahead safety: the published index (and every downstream signal) is
      lagged by one equity trading day, so a trade decided on day t uses only
      sentiment from day t-1 or earlier.

The lexicon itself is curated student work: candidate terms were generated by
an AI assistant, then reviewed, pruned, and valence-checked by hand against a
sample of real project headlines (see ai/log_sentiment_lexicon.md).
"""
