@lru_cache(maxsize=4)
def build_vader() -> object:
    """Return a plain VADER analyser (baseline)."""
    import nltk
    nltk.download("vader_lexicon", quiet=True)
    from nltk.sentiment.vader import SentimentIntensityAnalyzer
    return SentimentIntensityAnalyzer()


@lru_cache(maxsize=4)
def build_finsent() -> object:
    """Return a VADER analyser extended with the AlphaStream FinSent lexicon.

    Words update the analyser's own lexicon dict. Phrases need two steps:
    VADER only looks for a stored phrase where the token is already a
    dictionary hit, so each phrase's head word (its last token) must also have
    a tiny lexicon entry. Booster and phrase stores live on the analyser's
    constants object (NLTK >= 3.8) or as module globals (older NLTK).
    """
    import nltk
    nltk.download("vader_lexicon", quiet=True)
    from nltk.sentiment.vader import SentimentIntensityAnalyzer

    analyzer = SentimentIntensityAnalyzer()
    analyzer.lexicon.update(FINSENT_WORDS)

    constants = getattr(analyzer, "constants", None)
    if constants is None:
        import nltk.sentiment.vader as vader_module
        constants = vader_module

    phrase_store = getattr(constants, "SPECIAL_CASE_IDIOMS", None)
    if phrase_store is None:
        phrase_store = getattr(constants, "SPECIAL_CASES", {})
    booster_store = getattr(constants, "BOOSTER_DICT", {})

    for term, valence in FINSENT_PHRASES.items():
        head = term.split()[-1]
        if head not in analyzer.lexicon:
            analyzer.lexicon[head] = 0.1 if valence > 0 else -0.1
        if term not in phrase_store:
            phrase_store[term] = float(valence)

    for word, boost in FINSENT_BOOSTERS.items():
        if word not in booster_store:
            booster_store[word] = boost

    return analyzer


def score_text(analyzer: object, text: str) -> float:
    """Return the compound score (-1 to 1) for one text string."""
    if not text or not isinstance(text, str):
        return 0.0
    return float(analyzer.polarity_scores(text)["compound"])


def score_unique_titles(
    titles: pd.Series,
    *,
    cache_path: str | Path | None = None,
    analyzers: tuple[str, ...] = ("vader", "finsent"),
) -> pd.DataFrame:
    """Score every distinct headline once with the requested analyzers.

    Returns a DataFrame with columns [title, vader_compound, finsent_compound].
    If cache_path is given and holds all required titles, the cached frame is
    returned instead of re-scoring (build-time speed-up only).
    """
    unique = pd.Series(pd.unique(pd.Series(titles).dropna()), name="title")
    cache_path = Path(cache_path) if cache_path else None

    if cache_path is not None and cache_path.is_file():
        cached = pd.read_parquet(cache_path)
        if set(cached["title"]) >= set(unique):
            return cached

    out = pd.DataFrame({"title": unique})
    if "vader" in analyzers:
        vader = build_vader()
        out["vader_compound"] = [score_text(vader, t) for t in unique]
    if "finsent" in analyzers:
        finsent = build_finsent()
        out["finsent_compound"] = [score_text(finsent, t) for t in unique]

    if cache_path is not None:
        cache_path.parent.mkdir(parents=True, exist_ok=True)
        out.to_parquet(cache_path, index=False)
    return out


# ---------------------------------------------------------------------------
# Scoring and aggregation
# ---------------------------------------------------------------------------

def score_headlines(
    headlines: pd.DataFrame,
    equity_trading_dates: pd.DatetimeIndex,
    *,
    score_col: str = "finsent_compound",
    cache_path: str | Path | None = None,
) -> pd.DataFrame:
    """Score a cleaned headlines frame and return one row per headline.

    Returns a DataFrame with columns [date, ticker, sector, title,
    <score_col>], where date is the headline's aligned equity trading day.
    """
    trading_dates_sorted = pd.DatetimeIndex(sorted(equity_trading_dates))

    df = headlines.copy()
    df["date"] = pd.to_datetime(df["date"]).dt.tz_localize(None)
    idx = df["date"].map(
        lambda d: int(trading_dates_sorted.searchsorted(d, side="left"))
    ).to_numpy()
    idx = np.clip(idx, 0, len(trading_dates_sorted) - 1)
    df["trading_date"] = pd.DatetimeIndex([trading_dates_sorted[i] for i in idx])

    scored = score_unique_titles(df["title"], cache_path=cache_path)
    df = df.merge(scored, on="title", how="left")
    if score_col not in df.columns:
        raise ValueError(f"score_col {score_col!r} not produced by the analyzers")
    df[score_col] = df[score_col].fillna(0.0)
    out = df[["trading_date", "ticker", "sector", "title", score_col]].rename(
        columns={"trading_date": "date"}
    )
    return out.sort_values(["date", "ticker", "title"]).reset_index(drop=True)


def ticker_daily_sentiment(
    scored: pd.DataFrame,
    equity_trading_dates: pd.DatetimeIndex,
    *,
    score_col: str = "finsent_compound",
    lag: int = 1,
) -> pd.DataFrame:
    """Aggregate headline scores to a daily per-ticker panel.

    Returns a wide frame (date x ticker) of the mean compound score of each
    ticker's headlines aligned to its equity trading day. The frame is lagged
    by `lag` trading days so a decision on day t uses only sentiment from day
    t-lag or earlier. Ticker-days with no news carry NaN here (filled at the
    index stage).
    """
    daily = (
        scored.groupby(["date", "ticker"])[score_col]
        .mean()
        .reset_index()
    )
    wide = daily.pivot_table(index="date", columns="ticker", values=score_col)
    full_index = pd.DatetimeIndex(sorted(equity_trading_dates))
    wide = wide.reindex(full_index).sort_index()
    if lag > 0:
        wide = wide.shift(lag)
    return wide


def sector_sentiment_index(
    ticker_sentiment: pd.DataFrame,
    sector_map: pd.DataFrame,
    *,
    fill_missing: float = 0.0,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Build the equal-weight sector sentiment index and a coverage table.

    ticker_sentiment: wide frame (date x ticker), already lagged.
    sector_map: DataFrame with [ticker, sector].

    For each trading day and sector, the index is the mean sentiment across
    the sector's tickers, with no-news ticker-days contributing `fill_missing`
    (neutral). Returns (index_long, coverage) where index_long has columns
    [date, sector, sentiment, n_covered, n_total] and a separate market-wide
    mean is computed by the caller.
    """
    sectors = sorted(sector_map["sector"].unique())
    available = list(ticker_sentiment.columns)
    rows = []
    coverage_rows = []
    for sector in sectors:
        tickers = sorted(set(
            sector_map.loc[sector_map["sector"] == sector, "ticker"]
        ) & set(available))
        n_total = int(sector_map.loc[sector_map["sector"] == sector, "ticker"].nunique())
        if not tickers:
            continue
        sub = ticker_sentiment[tickers].fillna(fill_missing)
        index = sub.mean(axis=1)
        covered = ticker_sentiment[tickers].notna().sum(axis=1)
        for date in index.index:
            rows.append({"date": date, "sector": sector, "sentiment": float(index.loc[date])})
            coverage_rows.append({
                "date": date, "sector": sector,
                "n_covered": int(covered.loc[date]),
                "n_total": n_total,
            })
    index_long = pd.DataFrame(rows)
    coverage = pd.DataFrame(coverage_rows)
    return index_long, coverage


def build_sentiment_index(
    headlines: pd.DataFrame,
    equity_trading_dates: pd.DatetimeIndex,
    sector_map: pd.DataFrame,
    *,
    score_col: str = "finsent_compound",
    lag: int = 1,
    cache_path: str | Path | None = None,
) -> dict[str, pd.DataFrame]:
    """Run the full sentiment pipeline and return all derived panels.

    Returns a dict with:
        scored              : per-headline scores
        ticker_daily_lag    : lagged ticker-day sentiment (wide)
        index_long          : long sector index (lagged, tradeable)
        index_wide          : pivot date x sector of the lagged index
        market_index        : market-wide mean across sectors (date, sentiment)
        coverage            : per sector-day news coverage
    """
    scored = score_headlines(
        headlines, equity_trading_dates, score_col=score_col, cache_path=cache_path
    )
    ticker_daily = ticker_daily_sentiment(
        scored, equity_trading_dates, score_col=score_col, lag=lag)
    index_long, coverage = sector_sentiment_index(ticker_daily, sector_map)

    index_wide = index_long.pivot_table(
        index="date", columns="sector", values="sentiment"
    ).sort_index()
    market_index = index_wide.mean(axis=1).rename("sentiment").reset_index()
    return {
        "scored": scored,
        "ticker_daily_lag": ticker_daily,
        "index_long": index_long,
        "index_wide": index_wide,
        "market_index": market_index,
        "coverage": coverage,
    }
